CREATE TABLE income_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source_name varchar(120) NOT NULL,
    amount numeric(19,2) NOT NULL CHECK (amount > 0),
    frequency varchar(20) NOT NULL CHECK (frequency IN ('ONE_TIME', 'WEEKLY', 'BIWEEKLY', 'MONTHLY')),
    next_expected_date date NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL
);
CREATE INDEX idx_income_schedules_user_active_date ON income_schedules(user_id, active, next_expected_date);

CREATE TABLE goal_contributions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id bigint NOT NULL REFERENCES savings_goals(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    amount numeric(19,2) NOT NULL,
    goal_amount_after numeric(19,2) NOT NULL,
    source varchar(20) NOT NULL CHECK (source IN ('INITIAL', 'MANUAL', 'AUTOPAY', 'ADJUSTMENT')),
    reference varchar(120),
    created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_goal_contributions_goal_created ON goal_contributions(goal_id, created_at DESC, id DESC);

CREATE TABLE safe_to_spend_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    snapshot_date date NOT NULL,
    current_balance numeric(19,2) NOT NULL,
    safe_to_spend numeric(19,2) NOT NULL,
    breakdown text NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_safe_spend_snapshot_user_date UNIQUE (user_id, snapshot_date)
);
