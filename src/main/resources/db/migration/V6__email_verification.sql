ALTER TABLE users ADD COLUMN email_verified boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN email_verified_at timestamp(6);

CREATE TABLE email_verification_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash varchar(64) NOT NULL,
    expires_at timestamp(6) NOT NULL,
    used_at timestamp(6),
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_email_verification_token_hash UNIQUE (token_hash)
);
CREATE INDEX idx_email_verification_user_created ON email_verification_tokens(user_id, created_at DESC);
